-- ===================== unlock.lua - 分布式锁原子释放脚本 =====================
-- 【面试考点】为什么解锁需要Lua脚本（而不是直接DEL）？
--
-- 错误的做法（非原子，有安全漏洞）：
--   Java代码：
--     String val = redis.GET(lockKey)       // 步骤1：读取锁值
--     if (myThreadId.equals(val)) {          // 步骤2：判断是否是自己的锁
--         redis.DEL(lockKey)                 // 步骤3：删除锁
--     }
--
-- 漏洞场景（步骤2和步骤3之间发生以下情况）：
--   ① 线程A执行GET，得到自己的threadId，判断通过
--   ② 此时发生GC停顿 / 网络延迟，线程A被阻塞
--   ③ 锁的TTL到期，Redis自动删除了锁
--   ④ 线程B执行SETNX，成功获取了新锁
--   ⑤ 线程A恢复执行，执行DEL，把线程B的锁删掉了！
--   ⑥ 线程C获取锁成功，此时线程B和C同时持锁 → 并发安全被破坏！
--
-- 正确做法（Lua脚本原子执行GET+DEL，中间不可被打断）：
-- ======================================================================

-- KEYS[1]：锁的key（如 "lock:order:123"），由Java调用时传入
-- ARGV[1]：当前线程的锁值（如 "uuid-threadId"），由Java调用时传入

-- 比较：Redis中存储的锁值 vs 当前线程的锁值
-- 只有两者相等，才证明是自己持有的锁，才能执行删除
if(redis.call('get', KEYS[1]) == ARGV[1]) then
    -- 验证通过，原子地删除锁key，返回DEL的结果（删除成功返回1，key不存在返回0）
    return redis.call('del', KEYS[1])
end
-- 验证不通过（锁不是自己的，或锁已过期被删除），不执行删除，返回0
return 0
